create policy profiles_select_self
  on public.profiles for select to authenticated
  using (id = (select auth.uid()));

create policy advisories_read_published_or_utility_admin
  on public.advisories for select to anon, authenticated
  using (
    publication_status = 'published'
    or public.is_utility_admin(utility)
  );
create policy advisories_manage_utility
  on public.advisories for all to authenticated
  using (public.is_utility_admin(utility))
  with check (public.is_utility_admin(utility));

create policy work_orders_read_public
  on public.work_orders for select to anon, authenticated
  using (true);
create policy work_orders_manage_utility
  on public.work_orders for all to authenticated
  using (public.is_utility_admin(utility))
  with check (public.is_utility_admin(utility));

create policy reports_read_own_or_utility_admin
  on public.reports for select to authenticated
  using (
    user_id = (select auth.uid())
    or public.is_utility_admin(utility)
  );
create policy reports_create_own
  on public.reports for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1 from public.profiles
      where id = (select auth.uid()) and role = 'resident'
    )
  );
create policy reports_update_utility
  on public.reports for update to authenticated
  using (public.is_utility_admin(utility))
  with check (public.is_utility_admin(utility));

create policy network_readings_read_public
  on public.network_readings for select to anon, authenticated
  using (true);
create policy network_readings_manage_utility
  on public.network_readings for all to authenticated
  using (public.is_utility_admin(utility))
  with check (public.is_utility_admin(utility));

create policy ui_copy_read_public
  on public.ui_copy for select to anon, authenticated
  using (true);
