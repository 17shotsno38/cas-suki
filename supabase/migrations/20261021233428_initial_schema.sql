create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  email text not null,
  role text not null default 'resident' check (role in ('resident', 'admin')),
  utility text check (utility in ('CEPALCO', 'Water District')),
  phone_number text,
  address text,
  barangay text,
  district text,
  city text,
  postal_code text,
  profile_image text,
  sms_alerts boolean not null default true,
  notify_maintenance boolean not null default true,
  notify_email_digest boolean not null default true,
  immediate_email_alerts boolean not null default false,
  terms_accepted_at timestamptz,
  created_at timestamptz not null default now(),
  constraint profiles_role_utility_check check (
    (role = 'resident' and utility is null)
    or (role = 'admin' and utility is not null)
  )
);

create table public.advisories (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  title text not null,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  type text not null,
  area text not null,
  status text not null default 'Monitoring',
  details text not null,
  image_data_url text,
  latitude double precision,
  longitude double precision,
  scheduled_at timestamptz,
  publication_status text not null default 'published'
    check (publication_status in ('scheduled', 'publishing', 'published', 'failed')),
  channels text[] not null default '{}',
  created_at timestamptz not null default now(),
  constraint advisories_latitude_check check (latitude is null or latitude between -90 and 90),
  constraint advisories_longitude_check check (longitude is null or longitude between -180 and 180)
);

create table public.work_orders (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  title text not null,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  area text not null,
  description text not null,
  status text not null default 'Scheduled',
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint work_orders_time_check check (ends_at > starts_at)
);

create table public.reports (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  user_id uuid not null references public.profiles (id) on delete restrict,
  title text not null,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  area text not null,
  details text not null default '',
  status text not null default 'Received',
  created_at timestamptz not null default now()
);

create table public.network_readings (
  id bigint generated by default as identity primary key,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  district text not null,
  area text not null,
  pressure_psi double precision not null,
  reservoir_percent double precision not null
    check (reservoir_percent between 0 and 100),
  recorded_at timestamptz not null default now()
);

create table public.ui_copy (
  content_key text primary key,
  content_value text not null
);

create table public.portal_settings (
  portal text primary key check (portal in ('resident', 'cepalco', 'water')),
  settings_json jsonb not null
);

create table public.gmail_connections (
  utility text primary key check (utility in ('CEPALCO', 'Water District')),
  sender_email text not null,
  encrypted_refresh_token text not null,
  connected_by uuid not null references public.profiles (id) on delete restrict,
  connected_at timestamptz not null default now()
);

create table public.gmail_oauth_states (
  state_hash text primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  expires_at timestamptz not null
);

create table public.email_deliveries (
  id bigint generated by default as identity primary key,
  advisory_id bigint not null references public.advisories (id) on delete cascade,
  resident_id uuid not null references public.profiles (id) on delete cascade,
  status text not null check (status in ('pending', 'sent', 'failed')),
  error_message text,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (advisory_id, resident_id)
);

create table public.sms_deliveries (
  id bigint generated by default as identity primary key,
  advisory_id bigint not null references public.advisories (id) on delete cascade,
  resident_id uuid not null references public.profiles (id) on delete cascade,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  unique (advisory_id, resident_id)
);

create table public.schema_migrations (
  migration text primary key,
  applied_at timestamptz not null default now()
);

