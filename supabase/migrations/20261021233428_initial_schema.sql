  );

create policy sms_deliveries_read_resident_or_utility_admin
  on public.sms_deliveries for select to authenticated
  using (
    resident_id = (select auth.uid())
    or exists (
      select 1 from public.advisories
      where id = advisory_id
        and public.is_utility_admin(utility)
    )
  );
